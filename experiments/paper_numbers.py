#!/usr/bin/env python3
"""Export every headline number as a LaTeX macro, so the paper never contains a hand-typed result.

    python experiments/paper_numbers.py          # -> paper/numbers.tex, paper/numbers_index.md

In the paper:  \\input{numbers}  then  \\R{qwen2.5-7b/agent:full/feasible/all}  prints e.g. 87.5
Every key and its value is listed in paper/numbers_index.md.
"""

import json
import math
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]


def pct(v) -> str | None:
    if v is None or (isinstance(v, float) and math.isnan(v)):
        return None
    return f"{100 * float(v):.1f}"


def main() -> None:
    import argparse

    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--results", default="results")
    ap.add_argument("--out", default="paper")
    args = ap.parse_args()
    summ = json.loads((ROOT / args.results / "summary.json").read_text())
    vals: dict[str, str] = {}

    def put(key: str, value) -> None:
        if value is not None:
            vals[key] = str(value)

    for model, methods in summ.get("main", {}).items():
        for k, tiers in methods.items():
            for tier, d in tiers.items():
                put(f"{model}/{k}/feasible/{tier}", pct(d.get("feasible_mean")))
                put(f"{model}/{k}/feasible-std/{tier}", pct(d.get("feasible_std")))
                put(f"{model}/{k}/success5/{tier}", pct(d.get("success5_mean")))
                put(f"{model}/{k}/gap/{tier}", pct(d.get("gap_mean")))
                put(f"{model}/{k}/runs/{tier}", d.get("runs"))
                put(f"{model}/{k}/repeats/{tier}", d.get("repeats"))
    for model, comps in summ.get("gap1_tests", {}).items():
        for other, d in comps.items():
            put(f"{model}/gap1/vs-{other}/delta", pct(d.get("feasible_delta")))
            put(f"{model}/gap1/vs-{other}/p", f"{d.get('mcnemar_p'):.3g}")
            put(f"{model}/gap1/vs-{other}/pairs", d.get("pairs"))
            lo, hi = d.get("ci", [None, None])
            put(f"{model}/gap1/vs-{other}/ci-low", pct(lo))
            put(f"{model}/gap1/vs-{other}/ci-high", pct(hi))
    for model, d in summ.get("gap2_crosscheck", {}).items():
        for k in ("runs", "with_disagreements", "improved", "worsened"):
            put(f"{model}/gap2/{k}", d.get(k))
        for k in ("f1_first", "f1_final"):
            put(f"{model}/gap2/{k}", None if d.get(k) is None else f"{d[k]:.3f}")
    for model, methods in summ.get("by_style", {}).items():
        for k, d in methods.items():
            put(f"{model}/{k}/style-drop", pct(d.get("drop")))
            put(f"{model}/{k}/style-p", f"{d.get('p'):.3g}")
    for model, d in summ.get("gap3_drop_test", {}).items():
        put(f"{model}/gap3/drop-test-p", f"{d.get('wilcoxon_p'):.3g}")
    for model, methods in summ.get("ablation", {}).items():
        for k, d in methods.items():
            put(f"{model}/ablation/{k}/feasible", pct(d.get("feasible")))
            put(f"{model}/ablation/{k}/full", pct(d.get("full")))
            put(f"{model}/ablation/{k}/p", f"{d.get('p'):.3g}")
    for k, tiers in summ.get("classical", {}).items():
        for tier, d in tiers.items():
            put(f"classical/{k}/feasible/{tier}", f"{d['feasible']}/{d['n']}")
            put(f"classical/{k}/gap/{tier}", pct(d.get("gap_mean")))
    diff = ROOT / "results" / "benchmark" / "difficulty.csv"
    if diff.exists():
        d = pd.read_csv(diff)
        put("bench/scenarios", len(d))
        put("bench/test", int((d.split == "test").sum()))
        put("bench/dev", int((d.split == "dev").sum()))
        for tier in ("S", "M", "L"):
            s = d[d.tier == tier]
            put(f"bench/random-feasible/{tier}", pct(s.random_feasible.mean()))
            put(f"bench/auction-feasible/{tier}", f"{int(s.auction_feasible.sum())}/{len(s)}")
            put(f"bench/hungarian-feasible/{tier}", f"{int(s.hungarian_feasible.sum())}/{len(s)}")
        put("bench/auction-infeasible", int((~d.auction_feasible).sum()))
        put("bench/hungarian-infeasible", int((~d.hungarian_feasible).sum()))

    out = ROOT / args.out
    out.mkdir(parents=True, exist_ok=True)
    lines = ["% Generated by experiments/paper_numbers.py from results/summary.json. Do not edit by hand.",
             r"\makeatletter",
             r"\newcommand{\R}[1]{\@ifundefined{r@#1}{\textbf{??#1??}}{\@nameuse{r@#1}}}"]
    for k, v in sorted(vals.items()):
        lines.append(rf"\@namedef{{r@{k}}}{{{v}}}")
    lines.append(r"\makeatother")
    (out / "numbers.tex").write_text("\n".join(lines) + "\n")
    idx = ["# Numbers available as \\R{key} in the paper", "", "| key | value |", "|---|---|"]
    idx += [f"| `{k}` | {v} |" for k, v in sorted(vals.items())]
    (out / "numbers_index.md").write_text("\n".join(idx) + "\n")
    print(f"{len(vals)} numbers -> {out / 'numbers.tex'} (index: {out / 'numbers_index.md'})")


if __name__ == "__main__":
    sys.exit(main())
